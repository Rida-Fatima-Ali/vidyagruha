function buildForUser(user: AuthUser): AppNotification[] {
  const activity = activityForUser(user);
  switch (user.role) {
    case "student":
      return [...activity, ...COMMON, ...studentNotifications()];
    case "faculty":
      return [...activity, ...COMMON, ...facultyNotifications()];
    case "admin":
      return [...activity, ...COMMON, ...adminNotifications()];
  }
}

/** Per-user read state (keyed by role:id) so switching roles is isolated. */
const readState = new Map<string, Set<string>>();

function readKey(user: AuthUser): string {
  return `${user.role}:${user.id}`;
}

function applyReadState(user: AuthUser, items: AppNotification[]): AppNotification[] {
  const readIds = readState.get(readKey(user));
  if (!readIds) return items;
  return items.map((item) =>
    readIds.has(item.id) ? { ...item, read: true } : item,
  );
}

export function getMockNotificationsForUser(user: AuthUser): AppNotification[] {
  const items = buildForUser(user)
    .slice()
    .sort((a, b) => b.timestamp.localeCompare(a.timestamp));
  return applyReadState(user, items);
}

export function markAllMockNotificationsRead(user: AuthUser): void {
  const readIds = readState.get(readKey(user)) ?? new Set<string>();
  for (const item of buildForUser(user)) {
    readIds.add(item.id);
  }
  readState.set(readKey(user), readIds);
}
