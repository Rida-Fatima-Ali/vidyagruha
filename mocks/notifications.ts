function facultyNotifications(): AppNotification[] {
  const items: AppNotification[] = [];
  const dashboard = getMockFacultyDashboard();

  for (const submission of dashboard.submissions) {
    items.push({
      id: `fac-sub-${submission.id}`,
      category: "assignment",
      title: `${submission.subject} — pending submissions`,
      body: `${submission.pending} of ${submission.total} submissions for "${submission.assignmentTitle}" still need review.`,
      timestamp: "2026-08-14T16:00:00Z",
      read: false,
      priority: submission.pending > 3 ? "high" : "normal",
      subjectCode: submission.code,
    });
  }

  const unmarked = dashboard.classes.filter((c) => !c.attendanceMarked);
  if (unmarked.length > 0) {
    items.push({
      id: "fac-att-mark",
      category: "attendance",
      title: "Attendance not yet marked",
      body: `You have ${unmarked.length} class session${unmarked.length === 1 ? "" : "s"} today with attendance to record.`,
      timestamp: "2026-08-15T07:30:00Z",
      read: false,
      priority: "normal",
    });
  }

  for (const assignment of getAssignmentsForFaculty(DEMO_FACULTY_NAME)) {
    const daysLeft = Math.ceil(
      (new Date(assignment.dueDate).getTime() - DEMO_NOW.getTime()) / 86_400_000,
    );
    if (daysLeft <= 2) {
      items.push({
        id: `fac-asg-due-${assignment.id}`,
        category: "assignment",
        title: `"${assignment.title}" closes soon`,
        body: `Submissions close in ${daysLeft <= 0 ? "less than a day" : `${daysLeft} day${daysLeft === 1 ? "" : "s"}`}.`,
        timestamp: "2026-08-14T12:00:00Z",
        read: false,
        priority: "normal",
        subjectCode: assignment.code,
      });
    }
  }

  for (const atRisk of dashboard.atRisk.slice(0, 3)) {
    items.push({
      id: `fac-risk-${atRisk.code}-${atRisk.student.id}`,
      category: "attendance",
      title: `${atRisk.student.name} — attendance below threshold`,
      body: `${atRisk.subject} attendance is ${atRisk.percent}%, under the ${atRisk.threshold}% mark.`,
      timestamp: "2026-08-14T14:00:00Z",
      read: false,
      priority: "normal",
      subjectCode: atRisk.code,
    });
  }

  items.push({
    id: "fac-dl-ia1",
    category: "academic",
    title: "IA 1 marks due for departmental review",
    body: "IA 1 marks must reach the department office by Aug 18.",
    timestamp: "2026-08-14T10:00:00Z",
    read: false,
    priority: "normal",
  });

  return items;
}

