/**
 * Notifications are generated from the same mock sources the dashboard reads
 * (attendance, assignments, schedule overrides), so they can never contradict
 * the views they accompany. Each role sees only its own audience-scoped items —
 * e.g. a Microprocessor attendance alert belongs to the student (and its
 * faculty), never to an unrelated Python Lab faculty account.
 */

/* ------------------------------------------------------------------ */
/* Runtime activity notifications                                      */
/* ------------------------------------------------------------------ */

interface ActivityEntry extends AppNotification {
  audience: NotificationAudience;
  dedupeKey?: string;
}

/**
 * Notifications generated by real mutations during the demo session
 * (assignment published, submission received, schedule changed, notice/event
 * published, material uploaded, grade issued). Each carries an audience so a
 * students-only event never leaks into the faculty feed. Pushing an entry
 * with the same dedupe key refreshes the existing item instead of duplicating.
 */
const ACTIVITY: ActivityEntry[] = [];

export function pushActivityNotification(input: ActivityNotificationInput): void {
  const timestamp = DEMO_NOW.toISOString();
  const existingIndex = ACTIVITY.findIndex((item) => {
    if (input.dedupeKey) return item.dedupeKey === input.dedupeKey;
    return item.title === input.title && item.body === input.body;
  });
  if (existingIndex !== -1) {
    ACTIVITY[existingIndex] = {
      ...ACTIVITY[existingIndex],
      timestamp,
      read: false,
    };
    return;
  }
  ACTIVITY.unshift({
    id: `act-${Date.now().toString(36)}`,
    category: input.category,
    title: input.title,
    body: input.body,
    audience: input.audience ?? "all",
    priority: input.priority,
    subjectCode: input.subjectCode,
    dedupeKey: input.dedupeKey,
    timestamp,
    read: false,
  });
}

function activityForUser(user: AuthUser): AppNotification[] {
  return ACTIVITY.filter((item) => {
    if (item.audience === "all") return true;
    if (item.audience === "students") return user.role === "student";
    return item.audience === user.role;
  }).map((item) => ({ ...item }));
}

